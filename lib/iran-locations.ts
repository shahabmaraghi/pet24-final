export function isIranProvince(name?: string) {
  return IRAN_PROVINCES.some((item) => item.name === name);
}

export function citiesForProvince(province?: string) {
  return IRAN_PROVINCES.find((item) => item.name === province)?.cities || [];
}

export function isIranCity(province?: string, city?: string) {
  return Boolean(city && citiesForProvince(province).includes(city));
}

export function provinceForCity(city?: string) {
  if (!city) return "";
  return IRAN_PROVINCES.find((item) => item.cities.includes(city))?.name || "";
}

export function locationLabel(province?: string, city?: string) {
  if (province && city) return `${city}، ${province}`;
  return city || province || "";
}
